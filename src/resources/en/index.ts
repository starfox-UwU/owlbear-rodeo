/**
 * 把所有叶子节点放宽成 `string`。
 *
 * 基准字典用 `as const` 是为了拿到精确的键名（翻译键的类型安全就靠它），
 * 但键名精确的同时值也变成了字面量，中文会因此无法通过 `satisfies` 校验。
 * 这里只保留结构、放宽值类型。
 */
type DeepString<T> = {
  [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends object
    ? DeepString<T[K]>
    : T[K];
};

export default en;
